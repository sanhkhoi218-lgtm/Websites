create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 customer_name text not null,
 phone text not null,
 address text not null,
 payment_method text not null check(payment_method in ('cod','bank_transfer')),
 payment_status text not null default 'unpaid' check(payment_status in ('unpaid','pending','paid','refunded')),
 order_status text not null default 'new' check(order_status in ('new','confirmed','shipping','completed','cancelled')),
 items jsonb not null,
 total_amount bigint not null check(total_amount >= 0)
);
create table if not exists public.admin_users (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
alter table public.admin_users enable row level security;
drop policy if exists "public can create orders" on public.orders;
create policy "public can create orders" on public.orders for insert to anon, authenticated
with check(order_status='new' and payment_status='unpaid' and total_amount>=0);
drop policy if exists "admins can read orders" on public.orders;
create policy "admins can read orders" on public.orders for select to authenticated
using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "admins can update orders" on public.orders;
create policy "admins can update orders" on public.orders for update to authenticated
using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()))
with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
revoke all on public.admin_users from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant insert on public.orders to anon, authenticated;
grant select, update on public.orders to authenticated;
grant usage, select on sequence public.orders_id_seq to anon, authenticated;
